/**
 * Belirli bir emojinin açıklamasını getirir.
 * Varyasyon seçicilerini (\uFE0F) de normalize ederek tam eşleşme sağlar.
 */
export const getEmojiDescription = (emoji: string, lang: Language): string => {
  const clean = emoji.trim();
  if (!clean) return '';

  // Tam eşleşme
  if (emojiDescriptions[clean]) {
    return emojiDescriptions[clean][lang] || emojiDescriptions[clean].tr;
  }

  // Varyasyon seçici olmadan eşleşme
  const stripped = clean.replace(/\uFE0F/g, '');
  for (const [key, val] of Object.entries(emojiDescriptions)) {
    if (key.replace(/\uFE0F/g, '') === stripped) {
      return val[lang] || val.tr;
    }
  }

  // Bulunamazsa
  return lang === 'tr' ? 'Emoji' : 'Emoji';
};

/**
 * Bir emoji dizesini tek tek emojilere ayırır.
 */
export const parseEmojiString = (str: string): string[] => {
  if (!str) return [];
  // Boşlukla ayrılmışsa
  if (str.includes(' ')) {
    return str.split(/\s+/).filter(Boolean);
  }
  // Boşluksuz stringler için Intl.Segmenter fallback
  if (typeof Intl !== 'undefined' && Intl.Segmenter) {
    const segmenter = new Intl.Segmenter(undefined, { granularity: 'grapheme' });
    return Array.from(segmenter.segment(str), (s) => s.segment).filter((s) => s.trim());
  }
  return Array.from(str).filter((s) => s.trim());
};
